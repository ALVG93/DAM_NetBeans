    public boolean datosValidos() {
        if (!this.controladorClientes.nombreClienteValido(
                this.jTextNombreCompleto.getText().trim())) {
            return false;
        }
        
        if (!this.controladorClientes.anioNacimientoValido(
                this.jTextAnioNacimiento.getText().trim())) {
            return false;
        }
        
        if (!this.controladorClientes.provinciaValida(
                this.jTextProvincia.getText().trim())) {
            return false;
        }
        
        if (!this.controladorClientes.totalComprasValido(
                this.jTextTotalCompras.getText().trim())) {
            return false;
        }
        
        return true;
    }
    
    private void guardarCliente() {
        if (datosValidos()) {        
            this.nuevoCliente.setNombreCompleto(this.jTextNombreCompleto.getText().trim());
            this.nuevoCliente.setAnioNacimiento(Integer.parseInt(this.jTextAnioNacimiento.getText().trim()));
            this.nuevoCliente.setProvincia(this.jTextProvincia.getText().trim());
            this.nuevoCliente.setPremium(this.jCheckBoxPremium.isSelected());
            this.nuevoCliente.setTotalCompras(Double.parseDouble(this.jTextTotalCompras.getText().trim()));
            
            if (this.controladorClientes.altaCliente(this.nuevoCliente)) {
                dispose();
            }
        }
    }

